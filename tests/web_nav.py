"""Back/forward navigation in the web UI (desktop + phone)."""
import subprocess, os, shutil
from playwright.sync_api import sync_playwright
WS = "/tmp/ws"; shutil.rmtree(WS, ignore_errors=True); os.makedirs(WS); shutil.copy("/examples/hello.asm", WS)
srv = subprocess.Popen(["java", "-jar", "/build/mars-engine.jar", "--no-auth", "--port", "8098", "--root", WS, "--web", "/web"], stdout=subprocess.PIPE, text=True)
srv.stdout.readline(); srv.stdout.readline()
errors = []
def where(p): return p.evaluate("[MarsIDE.S.view, MarsIDE.S.m, document.querySelectorAll('.modal-bg').length, !!document.querySelector('.inspector')].join(' ')")
with sync_playwright() as pw:
    b = pw.chromium.launch(executable_path="/usr/bin/chromium", args=["--no-sandbox"])
    p = b.new_page(viewport={"width": 1400, "height": 860})
    p.on("pageerror", lambda e: errors.append(str(e)))
    p.goto("http://127.0.0.1:8098/"); p.wait_for_selector(".ftab"); p.wait_for_timeout(800)
    print("start        ", where(p))
    p.keyboard.press("F3"); p.wait_for_timeout(900);           print("assembled    ", where(p))
    p.click(".tab[data-v=labels]"); p.wait_for_timeout(300);   print("labels       ", where(p))
    p.click("tr.regrow[data-n='29']"); p.wait_for_timeout(300); print("inspector    ", where(p))
    p.click(".ins-mem"); p.wait_for_timeout(600);              print("show memory  ", where(p), p.evaluate("MIPS.hex(MarsIDE.R.mem.target)"))
    p.keyboard.press("Alt+ArrowLeft"); p.wait_for_timeout(500); print("back         ", where(p))
    p.keyboard.press("Alt+ArrowLeft"); p.wait_for_timeout(500); print("back         ", where(p))
    p.keyboard.press("Alt+ArrowLeft"); p.wait_for_timeout(500); print("back         ", where(p))
    p.keyboard.press("Alt+ArrowRight"); p.wait_for_timeout(500); print("forward      ", where(p))
    p.click("#btn-settings"); p.wait_for_timeout(300);         print("settings     ", where(p))
    p.go_back(); p.wait_for_timeout(400);                      print("back(closes) ", where(p))
    p.click("#btn-back"); p.wait_for_timeout(400);             print("‹ button     ", where(p))
    # F1 lookup from editor and back to the same cursor
    p.click(".tab[data-v=edit]"); p.wait_for_timeout(200)
    p.evaluate("const ta=document.querySelector('#editor textarea'); const i=ta.value.indexOf('syscall'); ta.focus(); ta.setSelectionRange(i,i); ta.dispatchEvent(new Event('keyup'))")
    sel = p.evaluate("document.querySelector('#editor textarea').selectionStart")
    p.keyboard.press("F1"); p.wait_for_timeout(400);           print("F1 card      ", where(p))
    p.keyboard.press("Alt+ArrowLeft"); p.wait_for_timeout(500)
    print("back to edit ", where(p), "cursor kept:", p.evaluate("document.querySelector('#editor textarea').selectionStart") == sel)
    p.close()
    m = b.new_context(viewport={"width": 390, "height": 844}, is_mobile=True, has_touch=True).new_page()
    m.on("pageerror", lambda e: errors.append(str(e)))
    m.goto("http://127.0.0.1:8098/"); m.wait_for_timeout(1500)
    m.tap("#bottomnav [data-m=regs]"); m.wait_for_timeout(200); print("m regs       ", where(m))
    m.tap("#bottomnav [data-m=io]"); m.wait_for_timeout(200);   print("m console    ", where(m))
    m.tap("#bottomnav [data-m=more]"); m.wait_for_timeout(300); print("m more sheet ", where(m))
    m.go_back(); m.wait_for_timeout(300);                       print("m back       ", where(m))
    m.go_back(); m.wait_for_timeout(300);                       print("m back       ", where(m))
    m.go_back(); m.wait_for_timeout(300);                       print("m back       ", where(m))
    m.evaluate("history.back()"); m.wait_for_timeout(400)
    print("m back (root)", where(m), "| state:", m.evaluate("JSON.stringify(history.state)"), "| toast:", m.evaluate("document.getElementById('toasts').textContent"))
    m.evaluate("history.back()"); m.wait_for_timeout(600)
    print("m back again ", m.url)
    b.close()
srv.terminate()
print("errors:", errors or "none")
