"""End-to-end test of the web UI with a real browser and the real engine."""
import subprocess, time, sys, os, shutil
from playwright.sync_api import sync_playwright

WS = "/tmp/ws"
shutil.rmtree(WS, ignore_errors=True); os.makedirs(WS)
for f in os.listdir("/examples"): shutil.copy(os.path.join("/examples", f), WS)
srv = subprocess.Popen(["java", "-jar", "/build/mars-engine.jar", "--no-auth", "--port", "8099", "--root", WS, "--web", "/web"],
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
print(srv.stdout.readline().strip()); print(srv.stdout.readline().strip())
SHOTS = "/shots"
errors = []

def shot(page, name):
    page.screenshot(path=f"{SHOTS}/{name}.png")
    print("shot", name)

with sync_playwright() as p:
    b = p.chromium.launch(executable_path="/usr/bin/chromium", args=["--no-sandbox"])
    # ---------------- desktop
    page = b.new_page(viewport={"width": 1400, "height": 860})
    page.on("console", lambda m: errors.append(f"console.{m.type}: {m.text}") if m.type in ("error", "warning") else None)
    page.on("pageerror", lambda e: errors.append(f"pageerror: {e}"))
    page.goto("http://127.0.0.1:8099/")
    page.wait_for_selector(".ftab", timeout=15000)
    page.wait_for_timeout(600)
    shot(page, "d1-editor")
    page.keyboard.press("F3"); page.wait_for_timeout(800)
    shot(page, "d2-assembled")
    for _ in range(5):
        page.keyboard.press("F7"); page.wait_for_timeout(150)
    shot(page, "d3-stepped")
    page.click("tr.regrow[data-f=gpr][data-n='2']"); page.wait_for_timeout(500)
    print("v0 meaning:", page.inner_text(".ins-meaning").replace("\n", " | "))
    shot(page, "d3b-v0-meaning")
    page.keyboard.press("Escape")
    page.click("tr.regrow[data-f=gpr][data-n='1']"); page.wait_for_timeout(600)
    print("at meaning:", page.inner_text(".ins-meaning").replace("\n", " | "))
    page.keyboard.press("Escape")
    page.keyboard.press("F5"); page.wait_for_timeout(700)
    shot(page, "d4-wants-input")
    page.fill("#stdin", "12"); page.press("#stdin", "Enter"); page.wait_for_timeout(800)
    shot(page, "d5-finished")
    page.click(".tab[data-v=mem]"); page.wait_for_timeout(500)
    shot(page, "d6-memory")
    page.fill("#mem-go", "result+4"); page.press("#mem-go", "Enter"); page.wait_for_timeout(600)
    page.click("td.target"); page.wait_for_timeout(300)
    shot(page, "d6b-mem-inspect")
    page.keyboard.press("Escape")
    page.click("#reg-nz"); page.wait_for_timeout(200)
    page.click("tr.regrow[data-n='29']"); page.wait_for_timeout(300)
    shot(page, "d6c-reg-inspect")
    page.click(".ins-mem"); page.wait_for_timeout(700)
    shot(page, "d6d-sp-memory")
    page.click("#reg-nz")
    page.click(".tab[data-v=edit]"); page.wait_for_timeout(200)
    page.keyboard.press("F10"); page.wait_for_timeout(500)
    shot(page, "d6e-zen")
    page.keyboard.press("Escape"); page.wait_for_timeout(300)
    assert not page.evaluate("MarsIDE.S.zen"), "zen should exit on Esc"
    page.click("#btn-settings"); page.wait_for_timeout(300)
    shot(page, "d7-settings")
    page.click(".theme-card[data-t=light]"); page.wait_for_timeout(200)
    page.keyboard.press("Escape"); page.click(".tab[data-v=edit]"); page.wait_for_timeout(300)
    shot(page, "d8-light-editor")
    # error marking
    page.click("#editor textarea"); page.keyboard.press("Control+End"); page.keyboard.type("\nbogus $t0, 5\naddi $t0, $t9\n")
    page.keyboard.press("F3"); page.wait_for_timeout(700)
    shot(page, "d9-errors")
    # reference card: F1 from the editor, filter, encoding, original PDF
    page.click(".tab[data-v=help]"); page.wait_for_timeout(300)
    shot(page, "d10-card")
    page.fill("#help-filter", "lw"); page.wait_for_timeout(200)
    page.click("#help-list tr[data-m=lw]"); page.wait_for_timeout(200)
    shot(page, "d11-card-lw")
    assert page.evaluate("fetch('ref/MIPS_Reference.pdf').then(r => r.headers.get('content-type'))") == "application/pdf"
    page.click(".tab[data-v=edit]"); page.click("#editor textarea")
    page.evaluate("const ta=document.querySelector('#editor textarea'); const p=ta.value.indexOf('syscall'); ta.setSelectionRange(p,p); ta.dispatchEvent(new Event('keyup'))")
    page.wait_for_timeout(200)
    hint = page.inner_text("#hint"); print("hint:", hint)
    page.keyboard.press("F1"); page.wait_for_timeout(400)
    shot(page, "d12-f1-syscall")
    page.click(".theme-card[data-t=amoled]") if page.query_selector(".theme-card") else None
    page.evaluate("MarsIDE.S.theme='amoled'; localStorage.clear()")
    page.close()
    shutil.copy("/examples/hello.asm", WS + "/hello.asm")
    # ---------------- phone
    ctx = b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2, is_mobile=True, has_touch=True)
    m = ctx.new_page()
    m.on("pageerror", lambda e: errors.append(f"pageerror(m): {e}"))
    m.goto("http://127.0.0.1:8099/")
    m.wait_for_timeout(800)
    m.evaluate("localStorage.clear()"); m.reload(); m.wait_for_timeout(1500)
    shot(m, "m1-editor")
    m.tap("#editor textarea"); m.wait_for_timeout(400)
    shot(m, "m1b-typing-keyrow")
    before = m.evaluate("MarsIDE && document.querySelector('#editor textarea').selectionStart")
    m.tap("#keybar [data-k=right]"); m.wait_for_timeout(100)
    after = m.evaluate("document.querySelector('#editor textarea').selectionStart")
    assert after == before + 1, f"cursor key failed {before}->{after}"
    m.tap("#keybar [data-k=rows]"); m.wait_for_timeout(300)
    shot(m, "m1c-keyrow-two-lines")
    m.tap("#keybar [data-k=rows]"); m.wait_for_timeout(100)
    m.tap("#keybar [data-k=kbd]"); m.wait_for_timeout(300)
    m.tap("[data-act=assemble]"); m.wait_for_timeout(900)
    shot(m, "m2-exec")
    m.tap("#bottomnav [data-m=regs]"); m.wait_for_timeout(300)
    m.tap("[data-act=step]"); m.wait_for_timeout(300)
    m.tap("[data-act=step]"); m.wait_for_timeout(300)
    shot(m, "m3-regs-stepped")
    m.tap("[data-act=run]"); m.wait_for_timeout(900)
    shot(m, "m4-console")
    m.fill("#stdin", "7"); m.press("#stdin", "Enter"); m.wait_for_timeout(700)
    shot(m, "m4b-console-done")
    m.tap("#bottomnav [data-m=mem]"); m.wait_for_timeout(600)
    shot(m, "m6-mem")
    m.tap("#bottomnav [data-m=more]"); m.wait_for_timeout(300)
    shot(m, "m5-more")
    b.close()
srv.terminate()
print("ERRORS:" if errors else "no browser errors", *errors[:20], sep="\n  ")
